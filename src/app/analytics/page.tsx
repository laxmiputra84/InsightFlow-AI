"use client";

import React, { useState } from "react";
import {
  Sparkles,
  Send,
  Bot,
  User,
  ArrowUpRight,
  TrendingDown,
  BarChart3,
  Table as TableIcon,
  Copy,
  Check,
  Download,
  Lightbulb,
  HelpCircle,
  RefreshCw,
} from "lucide-react";
import {
  ResponsiveContainer,
  BarChart,
  Bar,
  XAxis,
  YAxis,
  Tooltip,
  CartesianGrid,
  AreaChart,
  Area,
} from "recharts";
import { AppShell } from "@/components/layout/AppShell";
import { Button } from "@/components/ui/Button";
import { Badge } from "@/components/ui/Badge";
import { InsightFlowApi } from "@/services/api";
import { AiChatMessage } from "@/types";

const EXAMPLE_QUESTIONS = [
  "Why did sales decrease last month?",
  "Forecast revenue and margin through end of Q4",
  "Which customer segment had the highest churn risk?",
  "Analyze EMEA checkout conversion rate after CDN update",
];

const INITIAL_MESSAGES: AiChatMessage[] = [
  {
    id: "msg-init",
    sender: "assistant",
    timestamp: "10:30 AM",
    content:
      "Hello! I'm your Autonomous BI Analyst. Ask any natural language question regarding your company revenue, orders, margins, churn factors, or forward-looking projections.",
    findings: [
      "I have real-time access to the statistical models generated by the Root Cause, Forecasting, and Analyst Agents.",
      "Select a recommended question below or type your custom business prompt.",
    ],
    suggestedFollowUps: [
      "Why did sales decrease last month?",
      "Forecast revenue and margin through end of Q4",
      "Which customer segment had the highest churn risk?",
    ],
  },
];

export default function AnalyticsPage() {
  const [messages, setMessages] = useState<AiChatMessage[]>(INITIAL_MESSAGES);
  const [inputQuery, setInputQuery] = useState("");
  const [isSubmitting, setIsSubmitting] = useState(false);
  const [copiedId, setCopiedId] = useState<string | null>(null);

  const handleSend = async (queryToSend?: string) => {
    const q = (queryToSend || inputQuery).trim();
    if (!q || isSubmitting) return;

    const userMessage: AiChatMessage = {
      id: `user-${Date.now()}`,
      sender: "user",
      timestamp: new Date().toLocaleTimeString([], { hour: "2-digit", minute: "2-digit" }),
      content: q,
    };

    setMessages((prev) => [...prev, userMessage]);
    setInputQuery("");
    setIsSubmitting(true);

    try {
      const response = await InsightFlowApi.askAi(q);
      if (response.data) {
        setMessages((prev) => [...prev, response.data!]);
      } else {
        setMessages((prev) => [
          ...prev,
          {
            id: `err-${Date.now()}`,
            sender: "assistant",
            timestamp: new Date().toLocaleTimeString([], { hour: "2-digit", minute: "2-digit" }),
            content: response.error || "The AI analytics service is currently unavailable.",
          },
        ]);
      }
    } catch (err: any) {
      console.error("AI question failed:", err);
      setMessages((prev) => [
        ...prev,
        {
          id: `err-${Date.now()}`,
          sender: "assistant",
          timestamp: new Date().toLocaleTimeString([], { hour: "2-digit", minute: "2-digit" }),
          content: err?.message || "An error occurred while communicating with the agent swarm. Please try again.",
        },
      ]);
    } finally {
      setIsSubmitting(false);
    }
  };

  const copyToClipboard = (text: string, id: string) => {
    navigator.clipboard.writeText(text);
    setCopiedId(id);
    setTimeout(() => setCopiedId(null), 2000);
  };

  return (
    <AppShell>
      <div className="flex flex-col h-[calc(100vh-8rem)]">
        {/* Header Title */}
        <div className="flex items-center justify-between pb-4 border-b border-slate-800">
          <div>
            <h1 className="text-xl font-bold text-white flex items-center gap-2">
              <Sparkles className="h-5 w-5 text-indigo-400" />
              AI Conversational Analytics
            </h1>
            <p className="text-xs text-slate-400 mt-0.5">
              Natural language inquiry powered by autonomous diagnostic and forecasting agents
            </p>
          </div>
          <Badge variant="purple" size="md">
            Agent Reasoning Active
          </Badge>
        </div>

        {/* Chat / Analysis Feed */}
        <div className="flex-1 overflow-y-auto py-4 space-y-5 pr-1">
          {messages.map((msg) => (
            <div
              key={msg.id}
              className={`flex gap-3.5 ${
                msg.sender === "user" ? "justify-end" : "justify-start"
              }`}
            >
              {msg.sender === "assistant" && (
                <div className="flex h-9 w-9 shrink-0 items-center justify-center rounded-xl bg-gradient-to-tr from-indigo-600 to-cyan-500 text-white shadow-md shadow-indigo-500/20">
                  <Bot className="h-5 w-5" />
                </div>
              )}

              <div
                className={`max-w-3xl rounded-2xl p-5 shadow-lg ${
                  msg.sender === "user"
                    ? "bg-indigo-600 text-white ml-12"
                    : "border border-slate-800 bg-slate-900/90 text-slate-100 backdrop-blur-md"
                }`}
              >
                {/* Message Header */}
                <div className="flex items-center justify-between gap-4 pb-2 border-b border-slate-800/60 mb-3 text-xs">
                  <span className="font-semibold text-slate-300">
                    {msg.sender === "user" ? "You" : "InsightFlow Agent Swarm"}
                  </span>
                  <span className="text-[11px] text-slate-400">{msg.timestamp}</span>
                </div>

                {/* Content text */}
                <p className="text-sm leading-relaxed text-slate-200">{msg.content}</p>

                {/* Key Findings Bullet Cards */}
                {msg.findings && msg.findings.length > 0 && (
                  <div className="mt-4 space-y-2">
                    <span className="text-xs font-semibold uppercase tracking-wider text-indigo-300 flex items-center gap-1.5">
                      <Lightbulb className="h-3.5 w-3.5 text-indigo-400" />
                      Key Diagnostic Findings:
                    </span>
                    <div className="space-y-1.5">
                      {msg.findings.map((finding, idx) => (
                        <div
                          key={idx}
                          className="flex items-start gap-2.5 rounded-xl border border-slate-800 bg-slate-950/60 p-2.5 text-xs text-slate-200"
                        >
                          <span className="flex h-4 w-4 shrink-0 items-center justify-center rounded-full bg-indigo-500/20 text-[10px] font-bold text-indigo-400">
                            {idx + 1}
                          </span>
                          <span className="leading-snug">{finding}</span>
                        </div>
                      ))}
                    </div>
                  </div>
                )}

                {/* Metric Highlights */}
                {msg.metrics && msg.metrics.length > 0 && (
                  <div className="mt-4 grid grid-cols-2 sm:grid-cols-3 gap-3">
                    {msg.metrics.map((m, idx) => (
                      <div
                        key={idx}
                        className="rounded-xl border border-slate-800/80 bg-slate-950/60 p-3"
                      >
                        <span className="text-[11px] text-slate-400 block">{m.label}</span>
                        <span className="text-base font-bold text-white font-mono mt-0.5 block">
                          {m.value}
                        </span>
                        {m.change && (
                          <span className="text-[10px] font-semibold text-emerald-400 block mt-0.5">
                            {m.change}
                          </span>
                        )}
                      </div>
                    ))}
                  </div>
                )}

                {/* Embedded Chart */}
                {msg.chartData && (
                  <div className="mt-5 rounded-xl border border-slate-800 bg-slate-950/60 p-4">
                    <div className="flex items-center justify-between pb-3 border-b border-slate-800/80 mb-3">
                      <span className="text-xs font-semibold text-white flex items-center gap-1.5">
                        <BarChart3 className="h-4 w-4 text-cyan-400" />
                        {msg.chartData.title}
                      </span>
                    </div>

                    <div className="h-56 w-full">
                      <ResponsiveContainer width="100%" height="100%">
                        {msg.chartData.type === "bar" ? (
                          <BarChart
                            data={msg.chartData.data}
                            margin={{ top: 10, right: 10, left: -10, bottom: 0 }}
                          >
                            <CartesianGrid strokeDasharray="3 3" stroke="#1e293b" vertical={false} />
                            <XAxis
                              dataKey={msg.chartData.xAxisKey}
                              stroke="#64748b"
                              fontSize={11}
                              tickLine={false}
                            />
                            <YAxis stroke="#64748b" fontSize={11} tickLine={false} />
                            <Tooltip
                              content={({ active, payload, label }) => {
                                if (active && payload && payload.length) {
                                  return (
                                    <div className="rounded-xl border border-slate-700 bg-slate-900/95 p-2.5 text-xs text-white">
                                      <p className="font-semibold">{label}</p>
                                      <p className="text-indigo-300 font-mono">
                                        {payload[0].value?.toLocaleString()}
                                      </p>
                                    </div>
                                  );
                                }
                                return null;
                              }}
                            />
                            {msg.chartData.series.map((s) => (
                              <Bar
                                key={s.key}
                                dataKey={s.key}
                                name={s.name}
                                fill={s.color}
                                radius={[6, 6, 0, 0]}
                              />
                            ))}
                          </BarChart>
                        ) : (
                          <AreaChart
                            data={msg.chartData.data}
                            margin={{ top: 10, right: 10, left: -10, bottom: 0 }}
                          >
                            <CartesianGrid strokeDasharray="3 3" stroke="#1e293b" vertical={false} />
                            <XAxis
                              dataKey={msg.chartData.xAxisKey}
                              stroke="#64748b"
                              fontSize={11}
                              tickLine={false}
                            />
                            <YAxis stroke="#64748b" fontSize={11} tickLine={false} />
                            <Tooltip />
                            {msg.chartData.series.map((s) => (
                              <Area
                                key={s.key}
                                type="monotone"
                                dataKey={s.key}
                                name={s.name}
                                stroke={s.color}
                                fill={s.color}
                                fillOpacity={0.15}
                              />
                            ))}
                          </AreaChart>
                        )}
                      </ResponsiveContainer>
                    </div>
                  </div>
                )}

                {/* Embedded Table */}
                {msg.tableData && (
                  <div className="mt-4 overflow-x-auto rounded-xl border border-slate-800 bg-slate-950/60">
                    <table className="w-full text-left text-xs text-slate-300">
                      <thead className="border-b border-slate-800 bg-slate-900/80 text-slate-400 font-medium">
                        <tr>
                          {msg.tableData.columns.map((col, idx) => (
                            <th key={idx} className="p-2.5">
                              {col}
                            </th>
                          ))}
                        </tr>
                      </thead>
                      <tbody className="divide-y divide-slate-800/60 font-mono text-[11px]">
                        {msg.tableData.rows.map((row, rIdx) => (
                          <tr key={rIdx} className="hover:bg-slate-900/50">
                            {row.map((cell, cIdx) => (
                              <td key={cIdx} className="p-2.5">
                                {cell}
                              </td>
                            ))}
                          </tr>
                        ))}
                      </tbody>
                    </table>
                  </div>
                )}

                {/* Document Citations Grounding */}
                {msg.citations && msg.citations.length > 0 && (
                  <div className="mt-3.5 space-y-1.5 pt-2.5 border-t border-slate-800/60">
                    <span className="text-[10px] font-semibold text-slate-400 uppercase tracking-wider flex items-center gap-1">
                      <span className="h-1.5 w-1.5 rounded-full bg-indigo-400" />
                      Document Citations:
                    </span>
                    <div className="flex flex-wrap gap-2">
                      {msg.citations.map((c, cIdx) => (
                        <div
                          key={cIdx}
                          className="rounded-lg border border-slate-800 bg-slate-950/80 px-2 py-1 text-[11px] text-slate-300 font-mono"
                          title={c.snippet}
                        >
                          <span className="text-indigo-400 font-semibold">{c.documentName}</span>
                          {c.pageNumber ? ` (p. ${c.pageNumber})` : ` (chk #${c.chunkIndex + 1})`} •{" "}
                          <span className="text-emerald-400">{Math.round(c.relevanceScore * 100)}% match</span>
                        </div>
                      ))}
                    </div>
                  </div>
                )}

                {/* Data Source & Model Attribution Pill */}
                {msg.dataSource && (
                  <div className="mt-3.5 flex flex-wrap items-center gap-2 pt-2.5 border-t border-slate-800/60 text-[10px] text-slate-400 font-mono">
                    <span className="flex items-center gap-1 rounded bg-slate-950 px-2 py-0.5 border border-slate-800 text-slate-300">
                      <span className="h-1.5 w-1.5 rounded-full bg-emerald-400" />
                      Grounded: {msg.dataSource.database} ({msg.dataSource.tables.join(", ")})
                    </span>
                    <span className="rounded bg-indigo-500/10 px-2 py-0.5 border border-indigo-500/20 text-indigo-300">
                      Model: {msg.dataSource.modelUsed}
                    </span>
                    <span className="text-slate-500">
                      {msg.dataSource.groundedMetricsCount} metrics • {msg.dataSource.latencyMs}ms
                    </span>
                  </div>
                )}

                {/* Suggested follow-up prompt pills */}
                {msg.suggestedFollowUps && msg.suggestedFollowUps.length > 0 && (
                  <div className="mt-4 pt-3 border-t border-slate-800/80">
                    <span className="text-[11px] font-semibold text-slate-400 block mb-2">
                      Suggested follow-ups:
                    </span>
                    <div className="flex flex-wrap gap-2">
                      {msg.suggestedFollowUps.map((prompt, idx) => (
                        <button
                          key={idx}
                          onClick={() => handleSend(prompt)}
                          className="rounded-lg border border-indigo-500/25 bg-indigo-500/10 px-2.5 py-1 text-xs text-indigo-300 hover:bg-indigo-500/20 transition-colors text-left"
                        >
                          → {prompt}
                        </button>
                      ))}
                    </div>
                  </div>
                )}
              </div>

              {msg.sender === "user" && (
                <div className="flex h-9 w-9 shrink-0 items-center justify-center rounded-xl bg-slate-800 text-slate-300">
                  <User className="h-5 w-5" />
                </div>
              )}
            </div>
          ))}

          {isSubmitting && (
            <div className="flex gap-3.5 items-center rounded-2xl border border-indigo-500/30 bg-slate-900/90 p-4 shadow-lg text-xs text-indigo-300">
              <div className="flex h-8 w-8 shrink-0 items-center justify-center rounded-xl bg-indigo-600/30 text-indigo-400 animate-spin">
                <RefreshCw className="h-4 w-4" />
              </div>
              <div className="space-y-0.5">
                <p className="font-semibold text-white">Gemini Analyzing Business Metrics...</p>
                <p className="text-[11px] text-slate-400">
                  Querying verified MySQL ground-truth telemetry and synthesizing root-cause explanation.
                </p>
              </div>
            </div>
          )}
        </div>

        {/* Example Questions Bar */}
        <div className="py-2 flex items-center gap-2 overflow-x-auto no-scrollbar">
          <span className="text-[11px] font-semibold text-slate-400 shrink-0 flex items-center gap-1">
            <HelpCircle className="h-3 w-3 text-indigo-400" />
            Quick Prompts:
          </span>
          {EXAMPLE_QUESTIONS.map((q, idx) => (
            <button
              key={idx}
              onClick={() => handleSend(q)}
              className="shrink-0 rounded-lg border border-slate-800 bg-slate-900/90 px-2.5 py-1 text-xs text-slate-300 hover:border-indigo-500/50 hover:text-white transition-colors"
            >
              {q}
            </button>
          ))}
        </div>

        {/* Input Bar */}
        <div className="pt-2 border-t border-slate-800">
          <form
            onSubmit={(e) => {
              e.preventDefault();
              handleSend();
            }}
            className="flex items-center gap-2"
          >
            <input
              type="text"
              value={inputQuery}
              onChange={(e) => setInputQuery(e.target.value)}
              placeholder="Ask anything (e.g., 'Why did sales decrease last month?')"
              className="flex-1 rounded-xl border border-slate-800 bg-slate-900/90 px-4 py-3 text-sm text-slate-100 placeholder:text-slate-500 focus:border-indigo-500 focus:outline-none focus:ring-1 focus:ring-indigo-500 transition-colors shadow-inner"
            />
            <Button
              type="submit"
              variant="primary"
              size="lg"
              disabled={!inputQuery.trim() || isSubmitting}
              className="gap-2 shrink-0"
            >
              <span>Analyze</span>
              <Send className="h-4 w-4" />
            </Button>
          </form>
        </div>
      </div>
    </AppShell>
  );
}
